import { CARET } from './snippet';

export { CARET };

export type SymbolCategoryId =
  'functions' | 'structures' | 'greek' | 'operators' | 'relations' | 'arrows' | 'sets';

export interface MathSymbol {
  readonly label: string;
  readonly snippet: string;
  readonly title?: string;
}

export interface SymbolCategory {
  readonly id: SymbolCategoryId;
  readonly icon: string;
  readonly items: readonly MathSymbol[];
}

const sym = (label: string, command: string): MathSymbol => ({ label, snippet: `${command} ` });

const greek = (names: readonly [string, string][]): MathSymbol[] =>
  names.map(([label, name]) => sym(label, `\\${name}`));

const fn = (name: string, label = name): MathSymbol => ({ label, snippet: `\\${name}(${CARET})` });

